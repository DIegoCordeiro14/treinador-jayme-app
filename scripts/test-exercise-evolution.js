const E=require('./.tmp/ee/exercise-evolution-engine.js');
const S=require('./.tmp/ee/sport-types.js');
let pass=0,fail=0; const check=(n,c,x)=>{c?(pass++,console.log('  ✓ '+n)):(fail++,console.log('  ✗ '+n+(x?' → '+x:'')));};
const now=Date.now(),d=86400000,pt=(days,top,reps,vol,rir)=>({dateMs:now-days*d,topSetKg:top,topReps:reps,volumeKg:vol,avgRir:rir});
console.log('\n== computeExerciseEvolution ==');
let ev=E.computeExerciseEvolution([pt(90,70,10,2100,2),pt(60,75,10,2250,2),pt(30,80,10,2400,2),pt(5,82.5,10,2475,2)]);
check('carga subindo → progressing', ev.status==='progressing', ev.status);
check('topSetTrend positivo', ev.topSetTrendPct>0, String(ev.topSetTrendPct));
check('progressao por mes calculada', ev.progressionRatePctPerMonth!=null);
ev=E.computeExerciseEvolution([pt(40,80,8,2000,2),pt(30,80,8,2000,2),pt(20,80,8,2000,2),pt(5,80,8,2000,2)]);
check('estagnado 40d → platô', ev.status==='plateau', ev.status);
ev=E.computeExerciseEvolution([pt(30,85,8,2000,2),pt(5,78,8,1800,1)]);
check('caiu → regressing', ev.status==='regressing', ev.status);
check('1 sessão → insufficient', E.computeExerciseEvolution([pt(5,80,8,2000,2)]).status==='insufficient');
console.log('\n== computeMuscleGroupEvolution ==');
const up=E.computeExerciseEvolution([pt(90,70,10,2100,2),pt(5,82.5,10,2475,2)]);
const flat=E.computeExerciseEvolution([pt(40,60,10,1800,2),pt(5,60,10,1800,2)]);
let mg=E.computeMuscleGroupEvolution('chest',[{exerciseId:'a',name:'Supino',evolution:up},{exerciseId:'b',name:'Inclinado',evolution:flat}]);
check('grupo com 1/2 evoluindo → status calculado', ['boa_evolucao','estavel','atencao'].includes(mg.status), mg.status);
let weak=E.computeMuscleGroupEvolution('shoulders',[{exerciseId:'a',name:'Desenv',evolution:flat},{exerciseId:'b',name:'Elev',evolution:flat}]);
check('maioria estagnada + carga baixa → weakPointSignal', weak.weakPointSignal===true, JSON.stringify({s:weak.status,w:weak.weakPointSignal}));
console.log('\n== sport-types ==');
check('running → corrida (usa GPS)', S.normalizeSportType('Running')==='corrida' && S.sportUsesGps('corrida'));
check('strength → musculacao (sem GPS)', S.normalizeSportType('STRENGTH_TRAINING')==='musculacao' && !S.sportUsesGps('musculacao'));
check('jiu → jiujitsu', S.normalizeSportType('Brazilian Jiu-Jitsu')==='jiujitsu');
check('desconhecido → outro', S.normalizeSportType('xyz')==='outro');
console.log(`\n== RESULTADO: ${pass} passaram, ${fail} falharam ==\n`); process.exit(fail?1:0);
